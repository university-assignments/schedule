import { readJson, removeKey, writeJson } from '@/lib/persist';
import { today } from '@/lib/date';

/*
 * Короткая память о том, какую неделю человек смотрел.
 *
 * Задача ровно одна: случайное обновление страницы не должно перебрасывать с ноябрьской
 * недели на текущую. Человек листает расписание вперёд, задевает F5 (или браузер сам
 * перезагружает вкладку, вернувшуюся из фона) — и теряет место, на котором был.
 *
 * Но и помнить всегда нельзя, иначе завтра страница откроется на прошлой неделе, и
 * ошибка станет хуже исходной: расписание, открытое утром, должно показывать сегодня.
 * Отсюда десять минут — это «та же сессия», а не «моя настройка».
 */

const KEY = 'schedule:last-view:v1';
const TTL = 10 * 60 * 1000;

interface LastView
{
	date: string;
	/** Момент последнего касания: перелистнул неделю или ушёл со страницы. */
	at: number;
}

/**
 * Дата, на которую надо открыться, или null — если пауза затянулась и показывать надо
 * сегодняшний день.
 */
export function recallAnchor (): string | null
{
	const saved = readJson<LastView | null>(KEY, null);
	if (!saved?.date || typeof saved.at !== 'number') return null;

	/* Часы могли перевести назад (смена пояса, синхронизация времени): отрицательная
	   разница не должна читаться как «только что». */
	const elapsed = Date.now() - saved.at;
	if (elapsed < 0 || elapsed > TTL) return null;

	return saved.date;
}

/**
 * Запомнить дату и обновить отметку времени.
 *
 * Зовётся и при перелистывании, и при уходе со страницы — во втором случае важна именно
 * отметка: десять минут должны считаться от момента, когда вкладку закрыли, а не когда
 * открыли. Иначе у человека, читавшего расписание полчаса, обновление уже не вернуло бы
 * его на место, хотя он с этой недели и не уходил.
 */
export function rememberAnchor (date: string): void
{
	if (date === today())
	{
		/* Сегодняшний день — состояние по умолчанию, и запись о нём только мешала бы:
		   вернувшись кнопкой «Сегодня», человек при обновлении снова уехал бы на
		   отложенную неделю. */
		removeKey(KEY);
		return;
	}

	writeJson(KEY, { date, at: Date.now() } satisfies LastView);
}
