import axios from 'axios';

/*
 * Транспорт приложения. Сервера у него нет вовсе: «API» — это четыре статических файла
 * в public/data, которые Vite копирует в сборку как есть.
 *
 * baseURL собирается из BASE_URL, а не пишется строкой: на Pages приложение лежит в
 * подкаталоге /schedule/, локально — в корне дев-сервера. Захардкоженный путь работал бы
 * ровно в одном из двух мест.
 */
export const http = axios.create({
	baseURL: `${import.meta.env.BASE_URL}data/`,
	timeout: 15_000,
});

/*
 * Обход кэша GitHub Pages — самая неочевидная часть всей затеи.
 *
 * Pages отдаёт незахэшированные файлы с Cache-Control: max-age=600, а имена наших дампов
 * постоянны (data/schedule/<guid>.json). Значит после выгрузки человек ещё десять
 * минут смотрел бы вчерашнее расписание и видел бы над ним свежую отметку времени — то
 * есть ровно ту ошибку, от которой сайт и должен спасать.
 *
 * Разделение обязанностей такое:
 *  - meta.json тянется с t=Date.now(), то есть всегда мимо кэша. Он маленький.
 *  - дампы тянутся с v=<updatedAt из meta>, то есть кэшируются нормально, но адрес
 *    меняется ровно в момент обновления.
 *
 * Обратная сторона: пока meta не загружен, версии нет и запрашивать дамп нельзя —
 * поэтому запросы расписания в queries/ включаются только после meta.
 */
export function noCache (): Record<string, string>
{
	return { t: String(Date.now()) };
}

export function versioned (version: string | null): Record<string, string>
{
	// null бывает на свежем репозитории, где выгрузку ещё ни разу не запускали.
	return version ? { v: version } : noCache();
}
