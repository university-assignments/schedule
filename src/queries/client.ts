import { QueryClient } from '@tanstack/vue-query';

/*
 * Данные обновляются раз в несколько часов коммитом в репозиторий, а не поминутно.
 * Отсюда и настройки: агрессивно перепрашивать нечего, но и держать вечный кэш нельзя —
 * вкладку с расписанием держат открытой днями.
 *
 * refetchOnWindowFocus оставлен включённым намеренно: возвращение к вкладке — самый
 * частый момент, когда человек хочет увидеть актуальное. Запрос при этом уходит только
 * за meta.json (полкилобайта), а дампы перезапрашиваются, лишь если версия изменилась.
 */
export const queryClient = new QueryClient({
	defaultOptions: {
		queries: {
			staleTime: 5 * 60 * 1000,
			gcTime: 60 * 60 * 1000,
			retry: 1,
			refetchOnWindowFocus: true,
		},
	},
});
